import { loadEnvConfig } from "@next/env";
import { chromium, expect } from "@playwright/test";
loadEnvConfig(process.cwd(), true);

async function main() {
  const { getDatabase, closeDatabase } = await import("../src/lib/db");
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  const page = await browser.newPage();
  const registrationKeys: string[] = [];
  try {
    await page.goto("http://localhost:3000/registration/1");
    await expect(page).toHaveURL(/\/login$/);
    await page.getByLabel("อีเมลผู้ดูแลระบบ").fill(process.env.ADMIN_EMAIL!);
    await page.getByLabel("รหัสผ่าน", { exact: true }).fill(process.env.ADMIN_PASSWORD!);
    await page.getByRole("button", { name: "เข้าสู่ระบบ", exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await page.getByRole("navigation").getByRole("link", { name: "รายชื่อผู้ป่วย", exact: true }).click();
    await expect(page).toHaveURL(/\/registration$/);
    await expect(page.getByRole("heading", { name: "รายชื่อผู้ป่วย", exact: true }).first()).toBeVisible();
    await page.locator(".page-heading").getByRole("link", { name: "ลงทะเบียนผู้ป่วย", exact: true }).click();
    let previousHn = "";
    for (let index = 0; index < 2; index++) {
      if (index) await page.goto("http://localhost:3000/registration/new");
      registrationKeys.push(await page.locator('input[name="registration-key"]').inputValue());
      await expect(page.locator("#hn")).toHaveAttribute("readonly", "");
      await page.locator("#patient-type").selectOption("ผู้ป่วยใหม่");
      await page.locator("#first-name").fill("ทดสอบระบบ");
      await page.locator("#last-name").fill("ข้อมูลจำลอง");
      await page.locator("#birth-date").fill("2000-01-01");
      await page.locator("#phone").fill("0812345678");
      await page.locator("#department").selectOption(index === 0 ? "MS" : "TM");
      await page.locator("#bp-systolic").fill("120");
      await page.locator("#pulse").fill("72");
      await page.locator("#service-type").selectOption("course");
      await page.getByRole("button", { name: "บันทึกผู้ป่วย", exact: true }).click();
      await expect(page.locator(".form-error")).toContainText("ตัวบนและตัวล่าง");
      await expect(page.locator("#first-name")).toHaveValue("ทดสอบระบบ");
      await expect(page.locator("#pulse")).toHaveValue("72");
      await page.locator("#bp-diastolic").fill("80");
      await page.getByRole("button", { name: "บันทึกผู้ป่วย", exact: true }).click();
      await expect(page).toHaveURL(/\/registration\?saved=1$/);
      const record = await getDatabase().query("SELECT id::text, hn, details FROM rom_patient WHERE registration_key = $1", [registrationKeys[index]]);
      const hn: string = record.rows[0].hn;
      expect(hn).toMatch(/^CN-\d{6,}$/);
      if (previousHn) expect(BigInt(hn.slice(3))).toBeGreaterThan(BigInt(previousHn.slice(3)));
      previousHn = hn;
      expect(record.rows[0].details["bp-systolic"]).toBe("120");
      expect(record.rows[0].details["bp-diastolic"]).toBe("80");
      expect(record.rows[0].details.pulse).toBe("72");
      expect(record.rows[0].details["service-type"]).toBe("course");
      await page.getByLabel("ค้นหาผู้ป่วย").fill(hn);
      await expect(page).toHaveURL(new RegExp(`q=${hn}`));
      const row = page.getByRole("row").filter({ has: page.getByRole("cell", { name: hn, exact: true }) });
      await expect(row).toContainText("120/80");
      await expect(row.getByRole("combobox", { name: `ประเภทบริการ ${hn}`, exact: true })).toHaveValue("course");
      await row.getByRole("combobox", { name: `ประเภทบริการ ${hn}`, exact: true }).selectOption("walk-in");
      await expect(row.getByRole("status")).toContainText("บันทึกแล้ว");
      await expect(row.getByRole("cell", { name: "72", exact: true })).toBeVisible();
      await page.reload();
      await expect(row).toContainText("120/80");
      await row.getByRole("link", { name: `ดูรายละเอียด ${hn}`, exact: true }).click();
      await expect(page).toHaveURL(new RegExp(`/registration/${record.rows[0].id}\\?`));
      await expect(page.getByRole("heading", { name: "รายละเอียดผู้ป่วย", exact: true })).toBeVisible();
      await expect(page.getByRole("region", { name: "ข้อมูลสรุปผู้ป่วย" })).toContainText(hn);
      await expect(page.getByRole("region", { name: "ข้อมูลสรุปผู้ป่วย" })).toContainText("120/80");
      await expect(page.getByRole("heading", { name: "ผู้ติดต่อฉุกเฉิน / ผู้ปกครอง", exact: true })).toBeVisible();
      await expect(page.locator(".patient-detail-list").filter({ hasText: "ประเภทบริการ" })).toContainText("Walk-in");
      await page.reload();
      await expect(page.getByRole("region", { name: "ข้อมูลสรุปผู้ป่วย" })).toContainText("120/80");
      await page.setViewportSize({ width: 390, height: 844 });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      await page.setViewportSize({ width: 1280, height: 720 });
      await page.getByRole("link", { name: "กลับรายชื่อผู้ป่วย", exact: true }).click();
      await expect(page.getByLabel("ค้นหาผู้ป่วย")).toHaveValue(hn);
      await expect(row.getByRole("combobox", { name: `ประเภทบริการ ${hn}`, exact: true })).toHaveValue("walk-in");
      await expect(row).toContainText("120/80");
    }
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.goto("http://localhost:3000/registration/not-an-id");
    await expect(page.getByRole("heading", { name: "ไม่พบข้อมูลผู้ป่วย", exact: true })).toBeVisible();
    await page.goto("http://localhost:3000/registration/9223372036854775807");
    await expect(page.getByRole("heading", { name: "ไม่พบข้อมูลผู้ป่วย", exact: true })).toBeVisible();
    console.log("PASS: protected registration, automatic increasing CN, vital validation, retained fields, stored BP/pulse, directory display, search, reload, protected patient details, back navigation, missing patient handling, mobile layout.");
  } finally {
    await getDatabase().query("DELETE FROM rom_patient WHERE registration_key = ANY($1::uuid[])", [registrationKeys]);
    await browser.close();
    await closeDatabase();
  }
}
void main().catch(error => { console.error(error.message); process.exitCode = 1; });
